function onObjectLayerClick(el) {
    const objectId = el.dataset.objectId;
    if (!objectId) return;

    showZIndexLayerPicker().then(layer => {
        if (layer == null) return; // user cancelled

        // Update visible value
        el.textContent = layer;
        el.dataset.currentLayer = layer;

        // Update actual object
        const target = document.getElementById(objectId);
        if (target) {
            target.style.zIndex = layer;
        }

        // OPTIONAL: if you rely on existing logic
        // create a fake input to reuse onZIndexChanged
        if (typeof onZIndexChanged === "function") {
            const fakeInput = document.createElement("input");
            fakeInput.type = "number";
            fakeInput.value = layer;
            fakeInput.dataset.objectId = objectId;
            onZIndexChanged(fakeInput);
        }
    });
}

