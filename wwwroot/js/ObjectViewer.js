function OpenObjectViewer() {

    ObjectViewerOpen = true;

    DeselectAllObjects();

    var childSubContext = document.getElementsByClassName('SubContext');
    for (var i = 0; i < childSubContext.length; i++) {
        childSubContext[i].style.display = 'None';
    }

    StyleFormatContext = document.getElementById("ObjectViewerContext");
    StyleFormatContext.style.display = "block";
    StyleFormatContext.remove();
    document.getElementById("MultiContext").append(StyleFormatContext);

    var RightClickedObject = document.getElementById(RightClickedObjectId)

    if (!RightClickedObject) {
        CloseObjectViewer();
        return;
    }

    if (RightClickedObject.getAttribute('name') !== "GroupObject") {
        CloseObjectViewer();
        return;

    }
    ObjectViewerLoad(RightClickedObject);

    document.getElementById("MultiContext").style.display = 'block';
    document.getElementById("MultiContextDragLine").style.display = 'block';
    document.getElementById("MultiContextDragLine").addEventListener("mousedown", initDragDecorator, false);
}


let OV_dragged;
let OV_id;
let OV_index;
let OV_indexDrop;
let OV_list;

  document.addEventListener("dragstart", ({target}) => {
      OV_dragged = target;
      OV_id = target.id;
      OV_list = target.parentNode.children;
      for (let i = 0; i < OV_list.length; i += 1) {
          if (OV_list[i] === OV_dragged){
          OV_index = i;
        }
      }
  });

  document.addEventListener("dragover", (event) => {
      event.preventDefault();
  });

document.addEventListener("drop", ({ target }) => {

    var IsObjectViewerDropGroup = target.classList.contains("ObjectViewerDropGroup");
    var IsObjectViewerDrop = target.classList.contains("ObjectViewerDrop");

    if ((IsObjectViewerDropGroup || IsObjectViewerDrop) && target.parentElement.id !== OV_id) {

        if (IsObjectViewerDropGroup) {
            OV_list = target.children;
        }

        OV_dragged.remove(OV_dragged);

        for (let i = 0; i < OV_list.length; i += 1) {
                if (OV_list[i] === target.parentElement){
                OV_indexDrop = i;
            }
        }

        if (IsObjectViewerDropGroup) {

            var targetelementid = target.parentElement.id.replace("OV_", "");
            var draggedelementid = OV_id.replace("OV_", "");

            var targetelement = document.getElementById(targetelementid);
            var draggedelement = document.getElementById(draggedelementid);

            target.parentElement.getElementsByTagName('ul')[0].append(OV_dragged);

            targetelement.append(draggedelement);
        }
        else {

            var targetelementid = target.parentElement.id.replace("OV_", "");
            var draggedelementid = OV_id.replace("OV_", "");

            var targetelement = document.getElementById(targetelementid);
            var draggedelement = document.getElementById(draggedelementid);

            if (OV_index > OV_indexDrop) {
                target.parentElement.before(OV_dragged);
                targetelement.before(draggedelement);
            } else {
                target.parentElement.after(OV_dragged);
                targetelement.after(draggedelement);
            }

        }

        StopDragElement(); //resizing groups 

    }
});




