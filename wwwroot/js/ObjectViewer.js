function onZIndexChanged(input) {
    const objectId = input.dataset.objectId;
    if (!objectId) return;

    const el = document.getElementById(objectId);
    if (!el) return;

    let newZ = parseInt(input.value, 10);
    if (isNaN(newZ)) {
        newZ = 0;
        input.value = 0;
    }

    // ✅ Update live DOM
    el.style.zIndex = newZ;

    // OPTIONAL: if you want consistency
    // el.style.position ||= "relative";

    // OPTIONAL: persist elsewhere if needed
    // saveObjectZIndex(objectId, newZ);

    ObjectViewerLoad(ObjectViewerGroup);
}


function getZIndexLayerColor(layer) {
    if (layer === undefined || layer === null) return "#ffffff";

    let metadata = window.LayerSettings;

    // Handle JSON-string case safely
    if (typeof metadata === "string") {
        try {
            metadata = JSON.parse(metadata);
        } catch {
            return "#ffffff";
        }
    }

    if (!metadata || typeof metadata !== "object") {
        return "#ffffff";
    }

    const meta = metadata[layer];

    if (meta && typeof meta.color === "string" && meta.color.trim() !== "") {
        return meta.color;
    }

    return "#ffffff";
}

function openLayerColorPicker(el) {
    const layer = el.dataset.layer;
    if (!layer) return;

    // Create hidden color input once
    if (!window._layerColorPicker) {
        const input = document.createElement("input");
        input.type = "color";
        input.style.position = "fixed";
        input.style.left = "-9999px";
        input.style.top = "-9999px";

        input.addEventListener("change", () => {
            const layer = input.dataset.layer;
            if (!layer) return;

            const metadata = typeof window.LayerSettings === "string"
                ? JSON.parse(window.LayerSettings)
                : (window.LayerSettings || {});

            metadata[layer] = metadata[layer] || {};
            metadata[layer].color = input.value;

            window.LayerSettings = metadata;

            if (typeof UpdateLayerSettings === "function") {
                UpdateLayerSettings(metadata);
            }

            // Update all matching boxes instantly
            document.querySelectorAll(`.ObjectLayerColorBox[data-layer="${layer}"]`)
                .forEach(box => box.style.backgroundColor = input.value);
        });

        document.body.appendChild(input);
        window._layerColorPicker = input;
    }

    const picker = window._layerColorPicker;

    // Prepare picker for this layer
    picker.dataset.layer = layer;
    picker.value = getZIndexLayerColor(layer);

    // 🔔 Open native color picker
    picker.click();
}

